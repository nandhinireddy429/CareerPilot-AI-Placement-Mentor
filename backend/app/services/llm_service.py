import os
import requests
import json
import urllib3
from typing import List, Dict, Any, Optional
from dotenv import load_dotenv

# Disable SSL warnings
urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)

# Load env variables
load_dotenv(override=True)

class LLMService:
    def __init__(self):
        self.api_key = os.getenv("OPENROUTER_API_KEY")
        self.model = os.getenv("OPENROUTER_MODEL", "google/gemini-2.5-flash")
        self.endpoint = "https://openrouter.ai/api/v1/chat/completions"
        
        if not self.api_key:
            print("WARNING: OPENROUTER_API_KEY is not set in the environment or .env file.")

    def query(self, system_prompt: str, user_prompt: str, history: Optional[List[Dict[str, str]]] = None, temperature: float = 0.7) -> str:
        """
        Queries the OpenRouter API with a system prompt and user prompt, maintaining conversation history if provided.
        """
        if not self.api_key:
            return "Error: OpenRouter API key not configured. Please set it in your .env file."

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
            "HTTP-Referer": "http://localhost:8000",
            "X-Title": "CareerPilot AI"
        }

        messages = []
        messages.append({"role": "system", "content": system_prompt})

        # Append history if any
        if history:
            for message in history:
                messages.append({
                    "role": message.get("role", "user"),
                    "content": message.get("content", "")
                })

        messages.append({"role": "user", "content": user_prompt})

        payload = {
            "model": self.model,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": 400
        }

        try:
            response = requests.post(self.endpoint, headers=headers, json=payload, timeout=30, verify=False)
            if response.status_code == 200:
                data = response.json()
                choices = data.get("choices", [])
                if choices:
                    return choices[0].get("message", {}).get("content", "").strip()
                return "Error: No response generated by the model."
            elif response.status_code == 402:
                err_text = response.text
                print(f"OpenRouter Credit constraint triggered: {err_text}")
                import re
                match = re.search(r"can only afford (\d+)", err_text)
                if match:
                    affordable = int(match.group(1))
                    if affordable > 20:
                        retry_max = max(10, affordable - 15)
                        print(f"Retrying LLM query with self-healed token budget: {retry_max}")
                        payload["max_tokens"] = retry_max
                        retry_resp = requests.post(self.endpoint, headers=headers, json=payload, timeout=30, verify=False)
                        if retry_resp.status_code == 200:
                            data = retry_resp.json()
                            choices = data.get("choices", [])
                            if choices:
                                return choices[0].get("message", {}).get("content", "").strip()
                
                error_msg = f"HTTP Error {response.status_code}: {response.text}"
                print(f"OpenRouter API Error: {error_msg}")
                return f"Error communicating with AI service. Details: {response.text[:200]}"
            else:
                error_msg = f"HTTP Error {response.status_code}: {response.text}"
                print(f"OpenRouter API Error: {error_msg}")
                return f"Error communicating with AI service. Details: {response.text[:200]}"
        except Exception as e:
            print(f"LLM Query Exception: {e}")
            return f"Error: Request timed out or connection failed. Details: {str(e)}"

    def query_json(self, system_prompt: str, user_prompt: str, fallback_structure: Dict[str, Any], temperature: float = 0.2) -> Dict[str, Any]:
        """
        Helper method to request a JSON response from the LLM, parsing and falling back to a structured default if it fails.
        """
        json_system_prompt = system_prompt + "\nIMPORTANT: You must respond ONLY with a raw JSON object. Do not wrap it in markdown code blocks like ```json ... ```, do not include any explanatory text outside the JSON. Ensure the JSON conforms to the required fields."
        
        raw_response = self.query(json_system_prompt, user_prompt, temperature=temperature)
        
        # Clean response string of markdown formatting if any
        cleaned = raw_response.strip()
        if cleaned.startswith("```"):
            # Strip start
            lines = cleaned.splitlines()
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].startswith("```"):
                lines = lines[:-1]
            cleaned = "\n".join(lines).strip()

        try:
            return json.loads(cleaned)
        except Exception as e:
            print(f"Failed to parse LLM response as JSON. Raw output:\n{raw_response}\nError: {e}")
            
            # Simple heuristic cleaning: find the first '{' and last '}'
            try:
                start = cleaned.find('{')
                end = cleaned.rfind('}')
                if start != -1 and end != -1:
                    candidate = cleaned[start:end+1]
                    return json.loads(candidate)
            except Exception as e2:
                print(f"Secondary JSON parsing attempt failed: {e2}")
            
            return fallback_structure

# Global LLM instance
llm_service = LLMService()
